"""Writes UI/Map/OverlayData.lua: every area overlay of every zone map, from
the client's own tables (WorldMapOverlay, WorldMapOverlayTile, UiMapXMapArt),
for the "Always show the whole map" setting (UI/Map/Art.lua).

The tables come from wago.tools' DB2 exports for one build:

    python3 Dev/map_overlays.py 1.60.1.70291

Run it again for a new build when its zones change. An overlay is kept as
C_MapExplorationInfo.GetExploredMapTextures hands one back: its size, its
offset in the art layer's pixels and its tiles' files row by row.
"""

import csv
import io
import math
import os
import sys
import urllib.request

TABLES = ("WorldMapOverlay", "WorldMapOverlayTile", "UiMapXMapArt", "UiMap")
TILE = 256  # every classic zone layer's tile size
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UI", "Map", "OverlayData.lua")


def fetch(table, build):
    url = f"https://wago.tools/db2/{table}/csv?build={build}"
    request = urllib.request.Request(url, headers={"User-Agent": "social_diary map_overlays.py"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))


def main(build):
    overlays, tiles, map_art, maps = (fetch(t, build) for t in TABLES)
    names = {m["ID"]: m["Name_lang"] for m in maps}

    files = {}
    for t in tiles:
        if t["LayerIndex"] == "0":
            files.setdefault(t["WorldMapOverlayID"], {})[(int(t["RowIndex"]), int(t["ColIndex"]))] = t["FileDataID"]

    by_art = {}
    for o in overlays:
        w, h = int(o["TextureWidth"]), int(o["TextureHeight"])
        if w <= 0 or h <= 0 or o["PlayerConditionID"] != "0":
            continue
        grid = files.get(o["ID"], {})
        wide, tall = math.ceil(w / TILE), math.ceil(h / TILE)
        row_major = [grid.get((r, c)) for r in range(tall) for c in range(wide)]
        if None in row_major:
            print(f"overlay {o['ID']}: {len(grid)} of {wide * tall} tiles, left off", file=sys.stderr)
            continue
        by_art.setdefault(o["UiMapArtID"], []).append(
            (int(o["OffsetY"]), int(o["OffsetX"]), w, h, row_major))

    lines = [
        "-- Generated by Dev/map_overlays.py from build " + build + "'s WorldMapOverlay,",
        "-- WorldMapOverlayTile and UiMapXMapArt; do not edit by hand.",
        "--",
        "-- Every area overlay of a zone map, by uiMapID: { width, height, offsetX,",
        "-- offsetY, { file, ... } }, as C_MapExplorationInfo.GetExploredMapTextures",
        "-- hands back an explored one (UI/Map/Art.lua).",
        "",
        "local addonName, ns = ...",
        "",
        "ns.UI.MapOverlayData = {",
    ]
    count = 0
    for link in sorted(map_art, key=lambda m: int(m["UiMapID"])):
        if link["PhaseID"] != "0" or link["UiMapArtID"] not in by_art:
            continue
        lines.append(f"    [{link['UiMapID']}] = {{ -- {names.get(link['UiMapID'], '?')}")
        for y, x, w, h, ids in sorted(by_art[link["UiMapArtID"]]):
            lines.append(f"        {{ {w}, {h}, {x}, {y}, {{ {', '.join(ids)} }} }},")
            count += 1
        lines.append("    },")
    lines.append("}")
    with open(OUT, "w") as out:
        out.write("\n".join(lines) + "\n")
    print(f"{count} overlays on {sum(1 for l in lines if l.startswith('    ['))} maps -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
